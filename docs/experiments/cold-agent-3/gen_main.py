"""Generates vault/scenes/main.toml.

The HUD numeral needs ~32 stacked sprite layers and ~48 [[connect]] tables,
so it is generated rather than typed. Everything else is plain data.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "vault", "scenes", "main.toml")

# Screen standing point of the HUD anchor cell (7, 5) on an 8x6 ground with the
# default camera (centre = grid point (4, 3) at screen (320, 240)), 64x32 tiles.
ANCHOR = (7, 5)
CAM = (4, 3)
def standing_point(cell):
    gx, gy = cell[0] + 0.5, cell[1] + 0.5
    sx = ((gx - gy) - (CAM[0] - CAM[1])) * 32 + 320
    sy = ((gx + gy) - (CAM[0] + CAM[1])) * 16 + 240
    return sx, sy
SX, SY = standing_point(ANCHOR)

def offset_for(x, y, w, h):
    """Sprite offset that puts a w x h rect's top-left corner at screen (x, y)."""
    dx = x - SX + w / 2
    dy = y - SY + h
    return int(dx), int(dy)

# Seven-segment digit box (screen pixels).
L, T, W, H, t = 64, 16, 30, 54, 6
V = (H - 3 * t) // 2  # vertical segment length
SEG = {
    "a": (L + t, T, W - 2 * t, t),
    "b": (L + W - t, T + t, t, V),
    "c": (L + W - t, T + 2 * t + V, t, V),
    "d": (L + t, T + H - t, W - 2 * t, t),
    "e": (L, T + 2 * t + V, t, V),
    "f": (L, T + t, t, V),
    "g": (L + t, T + t + V, W - 2 * t, t),
}

COINS = ["coin1", "coin2", "coin3"]
PAIRS = [("coin1", "coin2"), ("coin1", "coin3"), ("coin2", "coin3")]

def short(c):
    return c[-1]

# Layers per segment, bottom first (file order = draw order on one cell: a later
# entity is drawn over an earlier one). The topmost *enabled* layer decides what the
# segment shows: a lit layer shows the segment, a cover (panel colour) hides it, and
# no enabled layer at all also leaves it dark. Each coin fires `collected` exactly
# once (it disables itself), so with n = coins collected so far:
#   Z     starts enabled, disabled by every coin      -> enabled iff n == 0
#   EVEN  starts enabled, toggled by every coin       -> enabled iff n in {0, 2}
#   ODD   starts disabled, toggled by every coin      -> enabled iff n in {1, 3}
#   Dk    starts enabled, disabled by coin k          -> enabled iff coin k missing
#   Pij   starts enabled, disabled by coin i or j     -> enabled iff coins i and j both missing
# Layer = (suffix, lit?, starts enabled?, [(coin, action), ...]).
def every(action):
    return [(c, action) for c in COINS]
Z = ("z", True, True, every("disable"))
EVEN = ("even", True, True, every("toggle"))
ODD = ("odd", True, False, every("toggle"))
BASE = ("base", True, True, [])
def D(k):
    return ("d" + short(k), False, True, [(k, "disable")])
def P(a, b):
    return ("p" + short(a) + short(b), False, True, [(a, "disable"), (b, "disable")])

LAYERS = {
    "a": [BASE, D("coin1"), D("coin2"), EVEN],   # lit for n != 1 (0, 2 via EVEN; 3 via base once D1, D2 are gone)
    "b": [BASE],                                 # lit for every n
    "c": [Z, ODD],                               # lit for n != 2
    "d": [BASE, D("coin1"), D("coin2"), EVEN],   # same as a
    "e": [EVEN],                                 # lit for n in {0, 2}
    "f": [Z],                                    # lit for n == 0
    "g": [BASE] + [P(a, b) for a, b in PAIRS],   # lit for n >= 2
}


def entity(name, prefab, rect, extra=""):
    x, y, w, h = rect
    dx, dy = offset_for(x, y, w, h)
    return (f'[[entity]]\nname = "{name}"\nprefab = "{prefab}"\npos = [{ANCHOR[0]}, {ANCHOR[1]}]\n'
            f'sprite = {{ size = [{w}, {h}], offset = [{dx}, {dy}] }}\n{extra}\n')

def self_check():
    """Simulate every order of every subset of pickups; the digit must depend only on n."""
    import itertools
    want = {0: set("abcdef"), 1: set("bc"), 2: set("abdeg"), 3: set("abcdg")}
    cases = 0
    for n in range(4):
        for order in itertools.permutations(COINS, n):
            lit = set()
            for seg, layers in LAYERS.items():
                top = None
                for suffix, is_lit, start, actions in layers:
                    on = start
                    for coin in order:
                        for c, act in actions:
                            if c == coin:
                                on = {"enable": True, "disable": False, "toggle": not on}[act]
                    if on:
                        top = is_lit
                if top:
                    lit.add(seg)
            assert lit == want[n], (n, order, lit)
            cases += 1
    print(f"self-check ok: all {cases} pickup orders show the right digit")

def main():
    self_check()
    out = []
    out.append('''# The vault. Generated by ../gen_main.py (the HUD needs many stacked layers);
# edit the generator, not this file.
#
# Grid: +x runs down-right on screen, +y down-left. Ground 8x6: cells (0, 0)..(7, 5).
# A wall of crates along x = 4 separates the hall (x 0..3) from the vault (x 5..7).
# The vault door at (4, 2) is TWO identical solid leaves on the same cell:
#   door_a is open only while plate_a is held, door_b only while plate_b is held,
# so the cell can be entered only while BOTH plates are held (slate has no AND:
# this is how the AND is built). This is why `slate check` reports W0201 here.
# Two sentry bots pace on and off the plates; the player (one body) can hold one plate.
#
# The coin counter (top-left) is a seven-segment digit built from rect sprites:
# slate has no text, no numbers and no counter, so each segment is a stack of
# layers that coin pickups disable or toggle, and the topmost enabled layer decides
# lit or dark. See gen_main.py for the truth table.

[scene]
name = "Vault"
doc = "The vault door opens only while both plates are held; a HUD digit counts the coins collected (0-3)."

[ground]
size = [8, 6]

[[entity]]
name = "player"
prefab = "player"
pos = [2, 2]

[[entity]]
name = "sentry_a"
prefab = "sentry"
pos = [0, 0]
patrol = { path = [[0, 0], [1, 0]], mode = "pingpong", step_frames = 60 }

[[entity]]
name = "sentry_b"
prefab = "sentry"
pos = [0, 5]
patrol = { path = [[0, 5], [1, 5]], mode = "pingpong", step_frames = 80 }

[[entity]]
name = "plate_a"
prefab = "plate"
pos = [1, 0]

[[entity]]
name = "plate_b"
prefab = "plate"
pos = [1, 5]

# Wall between hall and vault, with a gap for the door at (4, 2).
[[entity]]
prefab = "crate"
cells = [[4, 0], [4, 1], [4, 3], [4, 4], [4, 5]]

# The vault door: two identical leaves stacked on one cell (see the header).
[[entity]]
name = "door_a"
prefab = "door"
pos = [4, 2]

[[entity]]
name = "door_b"
prefab = "door"
pos = [4, 2]

[[entity]]
name = "coin1"
prefab = "coin"
pos = [2, 4]

[[entity]]
name = "coin2"
prefab = "coin"
pos = [2, 1]

[[entity]]
name = "coin3"
prefab = "coin"
pos = [6, 2]

[[connect]]
from = "plate_a"
signal = "pressed"
to = "door_a"
action = "disable"

[[connect]]
from = "plate_a"
signal = "released"
to = "door_a"
action = "enable"

[[connect]]
from = "plate_b"
signal = "pressed"
to = "door_b"
action = "disable"

[[connect]]
from = "plate_b"
signal = "released"
to = "door_b"
action = "enable"
''')
    for c in COINS:
        out.append(f'[[connect]]\nfrom = "{c}"\nsignal = "collected"\nto = "{c}"\naction = "disable"\n')

    out.append('\n# ---------------- HUD (screen top-left), anchored at cell (7, 5) and moved with sprite offsets.\n'
               '# Anchor (7, 5) has the largest x + y, so the HUD is drawn after everything else.\n')
    out.append(entity("hud_panel", "seg_off", (12, 8, 104, 70)))
    out.append(entity("hud_coin_icon", "seg_on", (26, 31, 24, 24)).replace(
        "sprite = {", 'sprite = { shape = "circle",'))
    connects = []
    for seg in "abcdefg":
        out.append(f"# segment {seg}\n")
        for suffix, is_lit, start, actions in LAYERS[seg]:
            name = f"hud_{seg}_{suffix}"
            extra = "" if start else "enabled = false\n"
            out.append(entity(name, "seg_on" if is_lit else "seg_off", SEG[seg], extra))
            for c, act in actions:
                connects.append(f'[[connect]]\nfrom = "{c}"\nsignal = "collected"\nto = "{name}"\naction = "{act}"\n')
    out.append("\n# ---------------- HUD wiring: what each coin pickup does to each HUD layer.\n")
    out.extend(connects)
    with open(OUT, "w") as f:
        f.write("\n".join(out))
    print("wrote", OUT, "with", len(connects), "HUD connections")

if __name__ == "__main__":
    main()
