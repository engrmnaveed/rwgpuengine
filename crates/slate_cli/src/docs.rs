/// What this version cannot do, with the known workarounds. Shown in the
/// project AGENTS.md and by `slate explain limits`. Keep it honest and
/// current: every limit an agent has to discover by experiment costs minutes.
pub const LIMITS_MD: &str = r##"Check this list before designing around a feature: if a requirement needs one of these, say so,
then build the closest honest approximation.

Supported (no workaround needed): text and numbers on screen (`label`, with `{prop}` placeholders), counters
and variables (`props` with `[[connect]]` `add`/`set`), conditions (`when` on `[[connect]]`: AND within one
connection, OR as several connections), a screen-space HUD (`screen_pos`), objects that hold pressure
plates (`pushable` crates the player pushes), terrain maps (`[ground] map` + `[[terrain]]`), multi-cell
objects (`footprint`), tapping the ground, building at runtime (`spawn` a prefab where the player taps,
with placement rules; `from_prefab` wires every copy), several actions for one signal (`actions = [...]`),
removing what the player taps (`disable` the copy:
it disappears and frees its cells), counting copies of a prefab (`counts`), and saying why a placement was
refused (the ground emits `refused` with the reason). See the Recipes.

| not in this version | what you can do instead (and what it costs) |
|---|---|
| **Expressions and arithmetic beyond add/set** (multiply, one prop from another, random numbers in data, "not equal" in `when`) | `add` a constant and `set` a constant; compare props with constants in `when` (`equals`, `at_least`, `at_most`). For a few fixed outcomes, write one `[[connect]]` per case with `when` conditions. For "any tool but Remove", write one connection per allowed value, or keep a flag prop that the buttons `set`. |
| **Timers and delays** | No timer component. A patrol stepping on and off a trigger fires on a fixed period (`step_frames`); use its `pressed` signal as the tick. |
| **Several independently controlled characters** (two players, co-op, switching characters, two people standing on plates at once) | Every enabled `mover` responds to the same input, so they move together. Use one mover; other characters are patrols or wanderers. Holding several plates at once is supported without characters: push crates onto them (`pushable`). |
| **Pulling, lifting, or pushing several crates in a row** | A mover pushes one `pushable` one cell; a crate with another crate behind it does not move (reason `push`). |
| **Text beyond printable ASCII** (accents, other scripts, emoji), fonts and text styles | One built-in pixel font: printable ASCII, a color and an integer `scale`. Other characters draw as a box (W0207). |
| **Image sprites, audio, animation** | Shapes only (`circle`, `rect`, `diamond`), colors, blocks, tiles and text. |
| **Rotation, scrolling camera** | Footprints are fixed: a 2 x 3 building is always 2 along x and 3 along y (make a second prefab for the turned one). The camera is fixed per scene. |
| **Dragging** (drag to build a row, drag to move a building) | Taps only: one tap, one `spawn`. Moving a building is clear (disable) and build again. |
| **A signal when a `when` stops something** ("not enough coins" as an event the game reacts to) | `skipped` is logged but emits nothing. Write the opposite case as its own `[[connect]]` on the same signal (`when = [{ ..., prop = "coins", at_most = 2 }]`). Refused *placements* do emit `refused`. |
| **Terrain that blocks walking** | `build = false` only stops spawning; movers walk on every terrain. Put solid entities (`cells = [...]`) where they must not walk. |
| **Deleting entities from the world's list** (removing what the player taps *is* supported, see above) | `disable` is the removal: a disabled copy takes no space, is not drawn and cannot be tapped, but stays in `inspect` (and keeps its id). |
| **Rust game code in a `slate new` project** | The engine supports Rust systems (`Game` trait), but `slate new` makes data-only projects and the CLI cannot load Rust code yet. Everything above is data. |

Behaviours worth knowing:
- Draw-order ties (same cell and height) go to file order: later entities are drawn on top.
- Enabling a solid entity on a cell where an actor stands does not push the actor out; it overlaps until the
  actor leaves.
- `changed` is only emitted when some `[[connect]]` listens to it, and only when the value really changes; the
  same goes for `spawned` and `refused`.
- `when = [{ reason = "terrain" }]` covers every terrain with `build = false`, so a lake and a path get the
  same message (the `blocked` event's `terrain` field says which one, for tests and `inspect`).
- A `counts` prop counts enabled copies anywhere, including ones on the screen (`screen_pos`); a disabled copy
  does not count.
- A tap on bare ground is a miss (`tap_miss`, with the `cell`) unless a `[[connect]] from = "ground"` listens.
"##;

