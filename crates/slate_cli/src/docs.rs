//! Generated documentation. Everything here is built from the registries
//! the engine itself runs on (commands, schemas, codes), so the docs always
//! match the installed version. `slate docs` prints them; `slate new`
//! writes the project AGENTS.md; the repo's docs/reference/ is checked
//! against them by a test.

use slate_core::codes;
use slate_data::schema::{self, Spec, spec_markdown};

use crate::args::{COMMANDS, command_text, usage_line};

const GENERATED: &str = "<!-- Generated by `slate docs`. Do not edit by hand. -->";

/// CLI reference.
pub fn cli_markdown() -> String {
    let mut out = format!(
        "{GENERATED}\n# slate {} command line\n\nEvery command accepts `--json` and then prints exactly one JSON object \
         on stdout with `slate`, `format`, `command`, `ok`, `errors`, `warnings` and `diagnostics` fields plus the \
         command's own fields. Exit codes: `0` ok, `1` errors or failed checks, `2` bad command line.\n\n",
        slate_core::ENGINE_VERSION
    );
    out.push_str("| command | what it does |\n|---|---|\n");
    for c in COMMANDS {
        out.push_str(&format!("| [`{}`](#slate-{}) | {} |\n", usage_line(c), c.name, c.summary));
    }
    for c in COMMANDS {
        out.push_str(&format!("\n## slate {}\n\n```text\n{}```\n", c.name, command_text(c)));
    }
    out
}

fn section(out: &mut String, h: &str, title: &str, intro: &str, specs: &[&Spec]) {
    out.push_str(&format!("\n{h} {title}\n\n{intro}\n\n"));
    let sub = format!("{h}#");
    for s in specs {
        out.push_str(&spec_markdown(s, &sub));
    }
}

/// File format reference.
pub fn formats_markdown() -> String {
    format!(
        "{GENERATED}\n# slate {} file formats\n\nAll files are TOML. Unknown keys are errors (E0103), never ignored. \
         Paths are relative to the project root (the folder with slate.toml).\n{}",
        slate_core::ENGINE_VERSION,
        formats_body("##")
    )
}

/// Format sections with headings at level `h` (`"##"`), specs one deeper.
pub fn formats_body(h: &str) -> String {
    let mut out = String::new();
    section(
        &mut out,
        h,
        "Project: slate.toml",
        "Marks the project root. Commands find it by walking up from the given path.",
        &[&schema::PROJECT_FILE, &schema::PROJECT, &schema::DISPLAY, &schema::ISO, &schema::SIM],
    );
    section(
        &mut out,
        h,
        "Scenes: scenes/*.toml",
        "A scene has optional `[scene]`, `[camera]` and `[ground]` tables, then any number of `[[entity]]` and \
         `[[connect]]` tables. Entities get ids 0, 1, 2, ... in file order (an entry with `cells` makes one entity \
         per cell).",
        &[&schema::SCENE_FILE, &schema::SCENE, &schema::CAMERA, &schema::GROUND, &schema::ENTITY, &schema::CONNECT],
    );
    section(
        &mut out,
        h,
        "Prefabs: prefabs/<name>.toml",
        "`prefab = \"wall\"` starts an entity from prefabs/wall.toml; keys on the entity override the prefab's, and \
         component tables merge key by key (`block = { color = \"#f00\" }` keeps the prefab's height).",
        &[&schema::PREFAB_FILE],
    );
    section(
        &mut out,
        h,
        "Components",
        "Tables an entity or prefab can carry. An empty table (`mover = {}`) adds the component with defaults.",
        schema::COMPONENT_SPECS,
    );
    section(
        &mut out,
        h,
        "Playtests: tests/*.toml",
        "Scripted input and checks, run by `slate test`. Any playtest can also drive `run`, `shot` and `inspect` \
         with `--input`.",
        &[&schema::PLAYTEST_FILE, &schema::TEST, &schema::INPUT, &schema::EXPECT, &schema::SHOT],
    );
    out.push_str(&semantics_markdown(h));
    out
}

/// How the pieces behave at runtime: frames, coordinates, signals, events.
pub fn semantics_markdown(h: &str) -> String {
    let event_table = slate_sim::events_markdown();
    format!(
        r#"
{h} Runtime rules

**Frames.** The simulation advances in fixed steps (`[sim] tick_rate` per second). Frame N is the state
after N steps. An `[[input]]` at frame N is applied by step N. `run --frames 300` takes 300 steps;
`shot --frame 300` and `inspect --frame 300` show the state after them. Everything is deterministic: same
files + input + seed = same state hash and same pixels, on every machine.

**Coordinates.** Cells are `[x, y]` integers; `[0, 0]` is the top corner of the ground. +x runs down-right
on screen, +y down-left, z is height. Direction inputs move movers: `up` = -y, `down` = +y,
`left` = -x, `right` = +x. Screen position of grid point (x, y, z), in pixels from the top-left:
`sx = ox + (x - y) × tile_width / 2`, `sy = oy + (x + y) × tile_height / 2 - z × z_height`, where (ox, oy) is
chosen so the camera `center` (default: the middle of the ground) lands in the middle of the frame. A sprite's
bottom edge sits at its cell's (sx, sy); `offset` shifts it. `slate inspect --json` shows each entity's
`screen` rectangle, which is the easiest way to place things.

**Step order.** Each step: input (taps resolve to the topmost enabled entity drawn under the point and
emit `tapped`), movers, patrols, wanderers, Rust game systems, triggers, then signal dispatch through
`[[connect]]` tables. A step that dispatches more than 1000 signals is cut off (E0301).

**Actors and blocking.** Entities with `mover`, `patrol` or `wander` are actors. A move is refused when
the target cell is outside the ground, holds an enabled `solid` entity, or holds another enabled actor.

**Enabled.** Disabled entities are not drawn, not solid, cannot be tapped, run no behaviors and do not
count for triggers. `[[connect]]` actions `enable`, `disable` and `toggle` change this. Enabling a solid
entity where an actor stands does not push the actor out.

**Input.** Every enabled `mover` responds to the same input. Only actors set off triggers.

**Signals.** Every entity emits `tapped` when tapped. A `trigger` emits `on_enter` (default `pressed`)
when its cell goes from empty to occupied by an enabled actor and `on_exit` (default `released`) when it
empties. Occupancy is re-checked every step, so enabling or disabling an actor that stands on the cell
counts too (the signal comes in the next step's trigger phase). A trigger that is already occupied at
frame 0 does **not** emit: start the connected door in the state you want (e.g. `enabled = false`), or use
a `when` condition, which looks at the current state rather than at signals.

**Props and conditions.** `[[connect]]` `add` and `set` change a prop of `to` (a prop's type is fixed by its
declared starting value). When the value really changes and some `[[connect]]` listens to `changed` from that
entity, it emits `changed`. Signals are dispatched first in, first out, each to its connections in file order,
within the same step. `when` conditions are checked as the signal is dispatched, against the state at that
moment (this step's positions and occupancy, plus the actions already applied in this step); if one fails,
nothing is done and a `skipped` event names the condition and what was seen.

**Events.** Every step logs what happened and what was refused, with a sentence and structured fields.
Read them with `slate inspect --events` or `slate run --events`; `slate explain events` prints this table.

{event_table}

**Drawing.** Ground first, then tiles, then blocks, sprites and labels back to front by `x + y`, then
height, then part (block, sprite, label), then file order (later entities on top). Screen entities
(`screen_pos`) are drawn after the whole world, in file order, and ignore the camera.
Blocks shade their left and right faces automatically. A sprite's bottom edge stands on its cell's center.
"#
    )
}

/// Error code reference.
pub fn errors_markdown() -> String {
    let mut out = format!(
        "{GENERATED}\n# slate {} diagnostic codes\n\nCodes are stable: never renumbered or reused. `E` codes are errors \
         (the command fails), `W` codes are warnings. `slate explain <CODE>` prints an entry.\n\n\
         | code | name | meaning |\n|---|---|---|\n",
        slate_core::ENGINE_VERSION
    );
    for c in codes::ALL {
        out.push_str(&format!("| [{}](#{}) | `{}` | {} |\n", c.code, c.code.to_lowercase(), c.slug, c.title));
    }
    for c in codes::ALL {
        out.push_str(&format!(
            "\n## {}\n\n**{}** (`{}`, {})\n\n{}\n",
            c.code,
            c.title,
            c.slug,
            c.severity.as_str(),
            c.explain
        ));
    }
    out
}

/// The AGENTS.md written into new projects: how to work, then the full
/// reference for this version. Written for an agent starting cold.
pub fn project_agents_md(project_name: &str) -> String {
    let v = slate_core::ENGINE_VERSION;
    let example = EXAMPLE_DOC.replace("{scene}", EXAMPLE_SCENE).replace("{test}", EXAMPLE_PLAYTEST);
    let limits = LIMITS_MD;
    let mut out = format!(
        r##"# AGENTS.md — {project_name}

This is a game project for **slate {v}**, an agent-native 2D/2.5D isometric engine. The game is text
files; the engine is a command line that checks, runs, renders and inspects them. This file was generated
for slate {v} (`slate docs --agents` prints the version you have installed).

## Work loop

0. Before designing, read **Limits in this version** below (also `slate explain limits`): some requirements
   need an approximation, and it is faster to know that up front.
1. Edit text files: `scenes/*.toml` (levels), `prefabs/*.toml` (reusable entities), `tests/*.toml` (playtests).
2. `slate check` — validates every file without running anything. Fix errors at the file:line it reports.
3. `slate test` — runs every playtest: scripted input, `[[expect]]` checks and reference screenshots.
4. Investigate instead of guessing:
   - `slate inspect --input tests/X.toml --frame N --events --entity NAME` — world state and the event log
     (every move, refusal, trigger, signal and action, each with a reason).
   - `slate shot --input tests/X.toml --report` — writes a PNG and lists what is drawn where, what is
     hidden and what is off-screen.
   - `slate run --input tests/X.toml --events` — run headless and print the state hash and events.
   - `slate explain CODE` (e.g. `slate explain E0201`) or `slate explain sprite` for any code or format.

Add `--json` to any command for one machine-readable JSON object. Exit code 0 = ok, 1 = errors or failed
checks, 2 = bad command line. Commands run from anywhere inside the project.

## Project layout

```text
slate.toml          project settings (display size, iso tile size, tick rate, seed)
scenes/main.toml    the main scene (set in slate.toml as main_scene)
prefabs/NAME.toml   entity templates, used as `prefab = "NAME"`
tests/NAME.toml     playtests (run by `slate test`)
tests/refs/*.png    reference screenshots for [[shot]] (create with `slate test --update-refs`)
out/                generated output (screenshots, diffs); safe to delete
```

{example}## Limits in this version

{limits}
## Recipes

slate has no built-in "goal", "door" or "item": you build them from tiles, blocks, sprites, triggers and
`[[connect]]`. These are the usual patterns.

- **Goal / win condition.** A tile with a trigger that only the player sets off, emitting its own signal:
  `tile = {{ color = "#f2e9a0" }}` + `trigger = {{ on_enter = "reached", only = "player" }}`. React with
  `[[connect]] from = "goal" signal = "reached" ...` (enable a flag, disable a gem). In the playtest, expect
  the player's `pos` on the goal and `event = "signal"` with `signal = "reached"`.
- **Door opened by a plate.** Plate: `tile` + `trigger = {{}}` (emits `pressed`/`released`). Door: a `block`
  with `solid = true`. Wire `from = "plate" signal = "pressed" to = "door" action = "disable"`. To close
  it again when the plate is left, add a second `[[connect]]` with `signal = "released"`, `action = "enable"`.
  A door that re-closes while an actor stands in its cell does not push it out; the actor can walk on.
- **Door that needs two plates held (AND).** Each plate's `pressed` opens the door only if the other plate
  is occupied, and either plate's `released` closes it:

  ```toml
  [[connect]]
  from = "plate_a"
  signal = "pressed"
  to = "door"
  action = "disable"
  when = [{{ entity = "plate_b", occupied = true }}]   # and the mirror image for plate_b

  [[connect]]
  from = "plate_a"
  signal = "released"
  to = "door"
  action = "enable"                                    # and the same for plate_b
  ```

  OR is several `[[connect]]` tables to the same target; NOT is `occupied = false` or `enabled = false`.
  **Who holds the plates?** One player can stand on only one plate, objects cannot hold plates, and every
  mover follows the same input (see Limits). So the second plate needs another actor: a patrol that paces onto
  it on a schedule, or a stationary one (see below) that a `[[connect]]` enables. And a player who holds one of
  the plates can never walk through the door, because stepping off closes it: if the player must get through,
  let actors hold both plates (e.g. taps or other plates enable stationary weights).
- **Collectible (counts once).** Put the sprite and the trigger on the **same** entity and connect its signal
  to itself: `trigger = {{ on_enter = "collected", only = "player" }}` +
  `[[connect]] from = "coin1" signal = "collected" to = "coin1" action = "disable"`. Disabling it also
  disables the trigger, so walking over the spot again does nothing. (A separate trigger left enabled would
  fire again.)
- **Score or counter.** Keep the number in a prop and `add` to it:
  `props = {{ coins = 0 }}` on a `hud` entity, then
  `[[connect]] from = "coin1" signal = "collected" to = "hud" action = "add" prop = "coins"` (`value`
  defaults to 1; `value = -1` subtracts). `set` replaces a value (`prop = "mode" value = "won"`).
- **Score on the screen (HUD).** An entity drawn at a fixed pixel with a backdrop and text:

  ```toml
  [[entity]]
  name = "hud"
  screen_pos = [8, 8]                                    # top-left pixel, ignores the camera
  sprite = {{ shape = "rect", color = "#000000aa", size = [65, 14] }}
  label = {{ text = "Coins: {{coins}}/3", offset = [3, 3] }} # {{coins}} shows the prop
  props = {{ coins = 0 }}
  ```

  Text is 6 px per character and 8 px tall at `scale = 1` (`slate explain label`). `slate shot --report` warns
  (W0305) if text runs off the frame or something covers it.
- **Do something when a count is reached.** The prop's owner emits `changed` whenever a prop changes; act on it
  with a condition: `[[connect]] from = "hud" signal = "changed" to = "vault" action = "disable"` +
  `when = [{{ entity = "hud", prop = "coins", at_least = 3 }}]`.
- **Stationary actor** (a weight on a plate, a hidden logic piece): `patrol = {{ path = [[x, y]] }}` with
  `pos = [x, y]`. It never moves and logs nothing, but it is an actor, so it holds a plate. A plate that is
  occupied from frame 0 does not emit `pressed`, so start its door already open (`enabled = false`), or
  enable the weight later with a `[[connect]]`.
- **Prove a score or a text**: `[[expect]] entity = "hud"` with `props = {{ coins = 3 }}` and/or
  `text = "Coins: 3/3"` (the label as shown). `slate inspect --entity hud` prints both.
- **Prove a condition stopped something**: `[[expect]] event = "skipped"`, `entity = "door"` (the target),
  `at_least = 1`; the event's message names the condition that failed.
- **Prove something is blocked** (a negative test): `[[expect]] event = "blocked"`, `entity = "player"`,
  `reason = "solid"` (reasons: `solid`, `actor`, `edge`, `area`, `cooldown`). Blocked *by whom*: add
  `other = "guard"`. With `event`, `entity` is the event's subject and `other` its other party;
  `slate explain events` lists both for every kind.
- **Prove something never happened**: `[[expect]] event = "signal"`, `entity = "goal"`, `signal = "reached"`,
  `at_most = 0`.
- **Buttons you tap.** Every entity emits `tapped` when tapped; wire it with `[[connect]]`. Get a pixel that
  is guaranteed to hit it from `slate inspect --entity lever --json` (field `tap`, also shown in the text
  table), then `[[input]] frame = 5` with `tap = [x, y]`. The tap point is for that frame: things in front
  of the entity can move.

## Tips

- **Mover timing.** A press or hold moves on its first frame (if the mover is ready), then every
  `step_frames` (default 8) while held, so `hold = "right"` with `for = 8 × N` gives exactly N steps. Input
  during the wait is not queued: a press is dropped (logged as `blocked`, reason `cooldown`); a hold moves as
  soon as the wait ends. Leave at least `step_frames` between separate inputs.
- **Timing puzzles.** Event-log entries are labeled with the step that produced them: `[N]` happened in step
  N, so it is visible from frame N + 1 (an `[[expect]]` at `frame = N + 1` counts it). `slate run --frames 200
  --track guard` prints the cells an entity occupies with frame ranges: read patrol windows there instead of
  guessing. Patrols and wanderers make their k-th step attempt in step k × step_frames − 1.
- To check a level is solvable, write a playtest that plays it and `[[expect]]` the end state, then add a
  `[[shot]]` and run `slate test --update-refs` once; look at the PNG before committing it.
- `main_scene` (slate.toml) is only the default for commands given no scene and the scene the web player opens
  first. Playtests should name their scene (`[test] scene = "scenes/level2.toml"`), so changing `main_scene`
  never changes what a test runs.
- `slate test` and `slate shot` warn when a sprite (W0302) or a trigger's tile (W0304) is mostly hidden
  behind blocks in front of it, or when something is off-screen (W0301/W0303). `slate shot --input
  tests/X.toml --frame N --report` lists what is drawn where.
- If something did not happen, the event log says why: a `blocked` event, a `signal` with no connections,
  a `skipped` connection whose `when` condition failed, or a tap that hit a disabled entity. `slate explain`
  with no topic lists everything it can explain.

"##
    );
    out.push_str("## Commands\n\n| command | what it does |\n|---|---|\n");
    for c in COMMANDS {
        out.push_str(&format!("| `{}` | {} |\n", usage_line(c), c.summary));
    }
    out.push_str("\n`slate help <command>` lists every flag.\n");
    out.push_str(
        "\n## File formats\n\nAll files are TOML. Unknown keys are errors (E0103), never ignored. Paths are relative \
                   to the project root.\n",
    );
    out.push_str(&formats_body("###"));
    out.push_str("\n## Diagnostic codes\n\n| code | meaning |\n|---|---|\n");
    for c in codes::ALL {
        out.push_str(&format!("| {} | {} |\n", c.code, c.title));
    }
    out.push_str("\n`slate explain <CODE>` explains a code and how to fix it.\n");
    out
}

