/// Drawn for characters the font does not have (W0207).
const MISSING: [u8; 8] = [0b11111, 0b10001, 0b10001, 0b10001, 0b10001, 0b10001, 0b11111, 0b00000];

/// Glyph index for a character: 0..95 for ' '..'~', 95 for the missing box.
pub fn glyph_index(c: char) -> u8 {
    let code = c as u32;
    if (0x20..=0x7e).contains(&code) { (code - 0x20) as u8 } else { 95 }
}

/// Is font pixel (col, row) of glyph `index` lit?
pub fn lit(index: u8, col: i32, row: i32) -> bool {
    if !(0..5).contains(&col) || !(0..8).contains(&row) {
        return false;
    }
    let rows = GLYPHS.get(index as usize).unwrap_or(&MISSING);
    rows[row as usize] & (0b10000 >> col) != 0
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_printable_glyph_except_space_has_pixels() {
        for (i, g) in GLYPHS.iter().enumerate() {
            let c = char::from_u32(0x20 + i as u32).unwrap();
            assert_eq!(g.iter().any(|r| *r != 0), c != ' ', "glyph {c:?}");
            assert!(g.iter().all(|r| *r < 32), "glyph {c:?} is wider than 5 pixels");
        }
    }

    #[test]
    fn glyphs_are_distinct() {
        for (i, a) in GLYPHS.iter().enumerate() {
            for (j, b) in GLYPHS.iter().enumerate().skip(i + 1) {
                assert_ne!(a, b, "{:?} and {:?}", (0x20 + i) as u8 as char, (0x20 + j) as u8 as char);
            }
        }
    }

    #[test]
    fn unknown_characters_draw_the_box() {
        assert_eq!(glyph_index('é'), 95);
        assert!(lit(95, 0, 0) && !lit(95, 2, 3));
        assert!(lit(glyph_index('|'), 2, 3));
    }
}
